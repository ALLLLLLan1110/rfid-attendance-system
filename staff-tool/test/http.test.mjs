import test from 'node:test';
import assert from 'node:assert/strict';
import { createStaffServer } from '../server.mjs';
import { fixture } from './fixture.mjs';
import http from 'node:http';

test('local HTTP workflow, write token, origin protection, backup and audit endpoints', async t => {
  const files = fixture();
  const { server } = createStaffServer({ ...files, port: 0 });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { if (server.listening) await new Promise(resolve => { server.close(resolve); server.closeIdleConnections(); }); files.cleanup(); });
  const address = `http://127.0.0.1:${server.address().port}`;
  const infoResponse = await fetch(`${address}/api/info`);
  const info = await infoResponse.json();
  assert.equal(info.application, 'rfid-staff-tool');
  const homepage = await fetch(address);
  assert.equal(homepage.status, 200);
  assert.match(await homepage.text(), /内部数据管理/);
  assert.match(homepage.headers.get('content-security-policy'), /frame-ancestors 'none'/);
  const noToken = await fetch(`${address}/api/backups`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(noToken.status, 403);
  const headers = { 'Content-Type': 'application/json', 'X-Staff-Token': info.token, Origin: address };
  const alien = await fetch(`${address}/api/backups`, { method: 'POST', headers: { ...headers, Origin: 'https://example.com' }, body: '{}' });
  assert.equal(alien.status, 403);
  const badHostStatus = await new Promise((resolve, reject) => {
    const request = http.get(`${address}/api/info`, { headers: { Host: 'example.com' } }, response => { response.resume(); resolve(response.statusCode); });
    request.on('error', reject);
  });
  assert.equal(badHostStatus, 403);
  const student = await (await fetch(`${address}/api/students/1`)).json();
  const saved = await fetch(`${address}/api/students/1`, { method: 'PUT', headers, body: JSON.stringify({ ...student, name: 'HTTP修改', reason: '接口验证' }) });
  assert.equal(saved.status, 200);
  const data = await saved.json();
  assert.equal(data.item.name, 'HTTP修改');
  const download = await fetch(`${address}/api/backup-file?file=${encodeURIComponent(data.backup.file)}`);
  assert.equal(download.status, 200);
  assert.equal(Buffer.from(await download.arrayBuffer()).subarray(0, 15).toString(), 'SQLite format 3');
  const traversal = await fetch(`${address}/api/backup-file?file=../../server.js`);
  assert.equal(traversal.status, 404);
  const changes = await (await fetch(`${address}/api/changes`)).json();
  assert.equal(changes.total, 1);
  const details = await (await fetch(`${address}/api/changes/${changes.items[0].id}`)).json();
  assert.equal(JSON.parse(details.before_json).name, '测试甲');
  const nonexistent = await fetch(`${address}/api/students/999`);
  assert.equal(nonexistent.status, 404);
  const malformed = await fetch(`${address}/api/students`, { method: 'POST', headers, body: '{' });
  assert.equal(malformed.status, 400);
  assert.equal((await (await fetch(`${address}/api/info`)).json()).stats.students, 2);
  const closed = new Promise(resolve => server.once('close', resolve));
  const quit = await fetch(`${address}/api/quit`, { method: 'POST', headers, body: '{}' });
  assert.equal(quit.status, 200);
  await closed;
});
